"""Assemble excluded ARMv7E-M DSP classes into a directed rejection table."""

import os
import struct
import subprocess
import tempfile
from pathlib import Path


def instructions():
    result = []

    def add(name, operands="r0, r1, r2"):
        result.append((name, f"{name} {operands}"))

    # QADD/QSUB/QDADD/QDSUB, SEL and parallel add/subtract are implemented.
    # The extends, packs and SSAT16/USAT16 are implemented.
    # SMLA<x><y> and SMUL<x><y> are implemented: Cortex-M4 app builds use them.
    for suffix in ["bb", "bt", "tb", "tt"]:
        add("smlal" + suffix, "r0, r3, r1, r2")
    # The dual, word and most-significant-word multiplies and USAD(A)8 are implemented.
    for name in ["smlald", "smlaldx", "smlsld", "smlsldx", "umaal"]:
        add(name, "r0, r3, r1, r2")
    return result


def main():
    root = Path(__file__).resolve().parent.parent
    entries = instructions()
    with tempfile.TemporaryDirectory() as temporary:
        directory = Path(temporary)
        source, obj, binary = [
            directory / name for name in ["excluded.s", "excluded.o", "excluded.bin"]
        ]
        source.write_text(
            ".syntax unified\n.thumb\n.cpu cortex-m4\n.text\n"
            + "\n".join(assembly for _, assembly in entries)
            + "\n"
        )
        subprocess.run(
            [os.environ.get("ARM_AS", "arm-none-eabi-as"), str(source), "-o", str(obj)], check=True
        )
        subprocess.run(
            [
                os.environ.get("ARM_OBJCOPY", "arm-none-eabi-objcopy"),
                "-O",
                "binary",
                str(obj),
                str(binary),
            ],
            check=True,
        )
        data = binary.read_bytes()
    if len(data) != len(entries) * 4:
        raise RuntimeError("expected exactly one 32-bit instruction per DSP mnemonic")
    output = [
        "/* SPDX-FileCopyrightText: 2026 Joshua Jun */",
        "/* SPDX-License-Identifier: Apache-2.0 */",
        "/* Generated by tools/build_excluded.py. */",
        "static const struct {",
        "    const char *name;",
        "    uint16_t first, second;",
        "} excluded[] = {",
        "    // clang-format off",
    ]
    for index, (name, _) in enumerate(entries):
        first, second = struct.unpack_from("<HH", data, index * 4)
        output.append(f'    {{"{name}", 0x{first:04x}, 0x{second:04x}}},')
    output.append("    // clang-format on\n};\n")
    (root / "tests/vectors/excluded.h").write_text("\n".join(output))
    print(f"{len(entries)} excluded DSP instructions")


if __name__ == "__main__":
    main()
