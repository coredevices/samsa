static void data_processing(void) {
    Fixture f;
    init(&f);
    /* AND shifted; ORN; TEQ; RSB */
    CODE(&f, 0xea01, 0x00c2, 0xea61, 0x0302, 0xea91, 0x0f02, 0xebc1, 0x0402);
    f.c.r[1] = 0x0f;
    f.c.r[2] = 3;
    EQ(samsa_run(&f.c, 4, NULL), SAMSA_STOP_BUDGET);
    EQ(f.c.r[0], 8);
    EQ(f.c.r[3], UINT32_MAX);
    EQ(f.c.r[4], 0xfffffff4);
    init(&f);
    CODE(&f, 0xea11, 0x0032); /* ands r0,r1,r2,rrx */
    f.c.r[1] = UINT32_MAX;
    f.c.r[2] = 3;
    samsa_set_xpsr(&f.c, 1u << 29);
    samsa_run(&f.c, 1, NULL);
    EQ(f.c.r[0], 0x80000001);
    EQ(samsa_get_xpsr(&f.c) >> 28, 10);
    init(&f);
    CODE(&f, 0xf04f, 0x20ff, 0xf011, 0x4000, 0xf111, 0x0201);
    f.c.r[1] = 0x7fffffff;
    samsa_run(&f.c, 1, NULL);
    EQ(f.c.r[0], 0xff00ff00);
    samsa_run(&f.c, 1, NULL);
    EQ(f.c.r[0], 0);
    EQ(samsa_get_xpsr(&f.c) >> 28, 6);
    samsa_run(&f.c, 1, NULL);
    EQ(f.c.r[2], 0x80000000);
    EQ(samsa_get_xpsr(&f.c) >> 28, 9);
    init(&f);
    CODE(&f, 0xf601, 0x20bc, 0xf6a1, 0x22bc, 0xf64a, 0x33cd, 0xf2c1, 0x2334);
    f.c.r[1] = 0x1000;
    samsa_run(&f.c, 4, NULL);
    EQ(f.c.r[0], 0x1abc);
    EQ(f.c.r[2], 0x544);
    EQ(f.c.r[3], 0x1234abcd);
    init(&f);
    CODE(&f, 0xf301, 0x0007, 0xf3a1, 0x1208, 0xf341, 0x2307, 0xf3c1, 0x2407, 0xf361, 0x250f, 0xf36f,
         0x250f);
    f.c.r[1] = 0xffffff80;
    f.c.r[5] = 0x12345678;
    samsa_run(&f.c, 1, NULL);
    EQ(f.c.r[0], 0xffffff80);
    samsa_run(&f.c, 1, NULL);
    EQ(f.c.r[2], 0);
    CHECK(samsa_get_xpsr(&f.c) & (1u << 27));
    samsa_run(&f.c, 3, NULL);
    EQ(f.c.r[3], UINT32_MAX);
    EQ(f.c.r[4], 255);
    EQ(f.c.r[5], 0x12348078);
    samsa_run(&f.c, 1, NULL);
    EQ(f.c.r[5], 0x12340078);
    init(&f);
    CODE(&f, 0xfa01, 0xf002, 0xfa31, 0xf302, 0xfa4f, 0xf491, 0xfa1f, 0xf5a1);
    f.c.r[1] = 0x123480fe;
    f.c.r[2] = 32;
    samsa_run(&f.c, 4, NULL);
    EQ(f.c.r[0], 0);
    EQ(f.c.r[3], 0);
    EQ(f.c.r[4], 0xffffff80);
    EQ(f.c.r[5], 0x1234);
    init(&f);
    CODE(&f, 0xfa91, 0xf081, 0xfa91, 0xf291, 0xfa91, 0xf3a1, 0xfa91, 0xf4b1, 0xfab1, 0xf581);
    f.c.r[1] = 0x123480fe;
    samsa_run(&f.c, 5, NULL);
    EQ(f.c.r[0], 0xfe803412);
    EQ(f.c.r[2], 0x3412fe80);
    EQ(f.c.r[3], 0x7f012c48);
    EQ(f.c.r[4], 0xfffffe80);
    EQ(f.c.r[5], 3);
}
static void multiply_divide(void) {
    Fixture f;
    init(&f);
    CODE(&f, 0xfb01, 0xf002, 0xfb01, 0x3402, 0xfb01, 0x3512, 0xfb81, 0x0602);
    f.c.r[1] = UINT32_MAX;
    f.c.r[2] = 3;
    f.c.r[3] = 7;
    samsa_run(&f.c, 4, NULL);
    EQ(f.c.r[0], 0xfffffffd);
    EQ(f.c.r[4], 4);
    EQ(f.c.r[5], 10);
    EQ(f.c.r[6], UINT32_MAX);
    init(&f);
    CODE(&f, 0xfba1, 0x0302, 0xfbe1, 0x0302, 0xfbc1, 0x0302);
    f.c.r[1] = UINT32_MAX;
    f.c.r[2] = 2;
    samsa_run(&f.c, 1, NULL);
    EQ(f.c.r[0], 0xfffffffe);
    EQ(f.c.r[3], 1);
    samsa_run(&f.c, 1, NULL);
    EQ(f.c.r[0], 0xfffffffc);
    EQ(f.c.r[3], 3);
    samsa_run(&f.c, 1, NULL);
    EQ(f.c.r[0], 0xfffffffa);
    EQ(f.c.r[3], 3);
    init(&f);
    CODE(&f, 0xfb91, 0xf0f2, 0xfbb1, 0xf3f2);
    f.c.r[1] = 0x80000000;
    f.c.r[2] = UINT32_MAX;
    samsa_run(&f.c, 2, NULL);
    EQ(f.c.r[0], 0x80000000);
    EQ(f.c.r[3], 0);
    f.c.r[15] = 0x1000;
    f.c.r[2] = 0;
    samsa_run(&f.c, 2, NULL);
    EQ(f.c.r[0], 0);
    EQ(f.c.r[3], 0);
}
static void memory(void) {
    Fixture f;
    init(&f);
    CODE(&f, 0xf8c1, 0x0100, 0xf8d1, 0x2100, 0xf851, 0x3d04, 0xf851, 0x4b04, 0xf851, 0x5e04, 0xf851,
         0x6027);
    f.c.r[0] = 0x12345678;
    f.c.r[1] = 0x1104;
    f.c.r[7] = 1;
    uint32_t v = 0xabcdef01;
    memcpy(f.mem + 0x100, &v, 4);
    memcpy(f.mem + 0x108, &v, 4);
    samsa_run(&f.c, 6, NULL);
    EQ(f.c.r[2], 0x12345678);
    EQ(f.c.r[3], v);
    EQ(f.c.r[4], v);
    EQ(f.c.r[5], v);
    EQ(f.c.r[6], v);
    EQ(f.c.r[1], 0x1104);
    init(&f);
    CODE(&f, 0xf991, 0x0100, 0xf931, 0x2013);
    f.c.r[1] = 0x1100;
    f.c.r[3] = 1;
    f.mem[0x200] = 0xfe;
    f.mem[0x102] = 0x01;
    f.mem[0x103] = 0x80;
    samsa_run(&f.c, 2, NULL);
    EQ(f.c.r[0], 0xfffffffe);
    EQ(f.c.r[2], 0xffff8001);
    init(&f);
    CODE(&f, 0xe9f1, 0x0202, 0xe861, 0x0202);
    f.c.r[1] = 0x1100;
    uint32_t words[] = {11, 22};
    memcpy(f.mem + 0x108, words, 8);
    samsa_run(&f.c, 1, NULL);
    EQ(f.c.r[0], 11);
    EQ(f.c.r[2], 22);
    EQ(f.c.r[1], 0x1108);
    f.c.r[0] = 33;
    samsa_run(&f.c, 1, NULL);
    EQ(f.c.r[1], 0x1100);
    EQ(word(&f, 0x108), 33);
    init(&f);
    CODE(&f, 0xe921, 0x0005, 0xe8b1, 0x000c);
    f.c.r[1] = 0x1110;
    f.c.r[0] = 123;
    f.c.r[2] = 456;
    samsa_run(&f.c, 2, NULL);
    EQ(f.c.r[2], 123);
    EQ(f.c.r[3], 456);
    EQ(f.c.r[1], 0x1110);
    /* uxtab r2, r2, r0; sxtah r0, r1, r2, ror #8 (ARMv7E-M) */
    init(&f);
    CODE(&f, 0xfa52, 0xf280, 0xfa01, 0xf092);
    f.c.r[0] = 0x12345678;
    f.c.r[1] = 10;
    f.c.r[2] = 0x100;
    EQ(samsa_run(&f.c, 1, NULL), SAMSA_STOP_BUDGET);
    EQ(f.c.r[2], 0x178);
    f.c.r[2] = 0x00ff8000;
    EQ(samsa_run(&f.c, 1, NULL), SAMSA_STOP_BUDGET);
    EQ(f.c.r[0], 0xffffff8a);
    /* smulbb r7, r5, r5; smlatb r0, r1, r2, r3, overflowing into Q (ARMv7E-M) */
    init(&f);
    CODE(&f, 0xfb15, 0xf705, 0xfb11, 0x3022);
    f.c.r[5] = 0xffff8000;
    f.c.r[1] = 0x7fff0000;
    f.c.r[2] = 2;
    f.c.r[3] = 0x7fffffff;
    EQ(samsa_run(&f.c, 1, NULL), SAMSA_STOP_BUDGET);
    EQ(f.c.r[7], 0x40000000);
    EQ(samsa_get_xpsr(&f.c) >> 27 & 1u, 0);
    EQ(samsa_run(&f.c, 1, NULL), SAMSA_STOP_BUDGET);
    EQ(f.c.r[0], 0x8000fffd);
    EQ(samsa_get_xpsr(&f.c) >> 27 & 1u, 1);
    /* STRD may store one register twice; LDRD may not load one twice. */
    init(&f);
    CODE(&f, 0xe9c7, 0x3302, 0xe9d7, 0x3302);
    f.c.r[7] = 0x1100;
    f.c.r[3] = 0x80000000;
    EQ(samsa_run(&f.c, 1, NULL), SAMSA_STOP_BUDGET);
    EQ(word(&f, 0x108), 0x80000000);
    EQ(word(&f, 0x10c), 0x80000000);
    EQ(samsa_run(&f.c, 1, NULL), SAMSA_STOP_UNDEF);
    init(&f);
    CODE(&f, 0xe9d1, 0x0200);
    f.c.r[1] = 0x1101;
    EQ(samsa_run(&f.c, 1, NULL), SAMSA_STOP_USAGE);
    init(&f);
    CODE(&f, 0xf891, 0xf010, 0xf991, 0xf010);
    f.c.r[1] = 0;
    EQ(samsa_run(&f.c, 2, NULL), SAMSA_STOP_BUDGET);
    init(&f);
    CODE(&f, 0xf8d1, 0xf000);
    f.c.r[1] = 0x1100;
    v = 0x1200;
    memcpy(f.mem + 256, &v, 4);
    EQ(samsa_run(&f.c, 1, NULL), SAMSA_STOP_USAGE);
    v |= 1;
    memcpy(f.mem + 256, &v, 4);
    EQ(samsa_run(&f.c, 1, NULL), SAMSA_STOP_BUDGET);
    EQ(f.c.r[15], 0x1200);
}
static void exclusive(void) {
    Fixture f;
    init(&f);
    CODE(&f, 0xe851, 0x0f01, 0xe841, 0x0201, 0xe841, 0x0301);
    f.c.r[1] = 0x1100;
    uint32_t v = 42;
    memcpy(f.mem + 0x104, &v, 4);
    samsa_run(&f.c, 1, NULL);
    EQ(f.c.r[0], 42);
    f.c.r[0] = 99;
    samsa_run(&f.c, 2, NULL);
    EQ(f.c.r[2], 0);
    EQ(f.c.r[3], 1);
    EQ(word(&f, 0x104), 99);
    init(&f);
    CODE(&f, 0xe8d1, 0x0f4f, 0xe8c1, 0x0f42, 0xe8d1, 0x3f5f, 0xf3bf, 0x8f2f, 0xe8c1, 0x3f52);
    f.c.r[1] = 0x1100;
    f.mem[256] = 77;
    samsa_run(&f.c, 2, NULL);
    EQ(f.c.r[0], 77);
    EQ(f.c.r[2], 0);
    samsa_run(&f.c, 3, NULL);
    EQ(f.c.r[3], 77);
    EQ(f.c.r[2], 1);
}
static void control(void) {
    Fixture f;
    init(&f);
    CODE(&f, 0xf000, 0xf802, 0xbf00, 0xbf00, 0x4770);
    samsa_run(&f.c, 1, NULL);
    EQ(f.c.r[15], 0x1008);
    EQ(f.c.r[14], 0x1005);
    samsa_run(&f.c, 1, NULL);
    EQ(f.c.r[15], 0x1004);
    init(&f);
    CODE(&f, 0xf000, 0xb802);
    samsa_run(&f.c, 1, NULL);
    EQ(f.c.r[15], 0x1008);
    init(&f);
    CODE(&f, 0xf000, 0x8002);
    samsa_set_xpsr(&f.c, 1u << 30);
    samsa_run(&f.c, 1, NULL);
    EQ(f.c.r[15], 0x1008);
    init(&f);
    CODE(&f, 0xf380, 0x8800, 0xf3ef, 0x8100, 0xf3bf, 0x8f5f);
    f.c.r[0] = 0xf8000000;
    samsa_run(&f.c, 3, NULL);
    EQ(f.c.r[1], 0xf8000000);
    /* msr APSR_nzcvqg,r0; msr APSR_g,r2; mrs r1,APSR (DSP GE bits 19:16) */
    init(&f);
    CODE(&f, 0xf380, 0x8c00, 0xf382, 0x8400, 0xf3ef, 0x8100);
    f.c.r[0] = 0xffffffff;
    f.c.r[2] = 0x000a0000;
    EQ(samsa_run(&f.c, 1, NULL), SAMSA_STOP_BUDGET);
    EQ(samsa_get_xpsr(&f.c), 0xf90f0000);
    EQ(samsa_run(&f.c, 2, NULL), SAMSA_STOP_BUDGET);
    EQ(f.c.r[1], 0xf80a0000);
    samsa_set_xpsr(&f.c, 0x00050000);
    EQ(samsa_get_xpsr(&f.c), 0x01050000);
    samsa_reset(&f.c);
    EQ(samsa_get_xpsr(&f.c), 0x01000000);
    init(&f);
    CODE(&f, 0xf380, 0x8000);
    EQ(samsa_run(&f.c, 1, NULL), SAMSA_STOP_UNDEF);
    init(&f);
    CODE(&f, 0xf3ef, 0x8010);
    EQ(samsa_run(&f.c, 1, NULL), SAMSA_STOP_UNDEF);
    init(&f);
    CODE(&f, 0xe8d1, 0xf002);
    f.c.r[1] = 0x1100;
    f.c.r[2] = 1;
    f.mem[257] = 7;
    samsa_run(&f.c, 1, NULL);
    EQ(f.c.r[15], 0x1012);
    init(&f);
    CODE(&f, 0xe8df, 0xf012, 0x0000, 0x0005);
    f.c.r[2] = 1;
    samsa_run(&f.c, 1, NULL);
    EQ(f.c.r[15], 0x100e);
    init(&f);
    CODE(&f, 0xee00, 0x0000);
    EQ(samsa_run(&f.c, 1, NULL), SAMSA_STOP_UNDEF);
}
static void unaligned_pc_table(void) {
    Fixture f;
    init(&f);
    CODE(&f, 0xbf00, 0xe8df, 0xf012, 0x0000, 0x0005);
    f.c.r[2] = 1;
    EQ(samsa_run(&f.c, 2, NULL), SAMSA_STOP_BUDGET);
    EQ(f.c.r[15], 0x1010);
    init(&f);
    CODE(&f, 0xbf00, 0xe8df, 0xf002, 0x0500);
    f.c.r[2] = 1;
    EQ(samsa_run(&f.c, 2, NULL), SAMSA_STOP_BUDGET);
    EQ(f.c.r[15], 0x1010);
}
int main(void) {
    data_processing();
    multiply_divide();
    memory();
    exclusive();
    control();
    unaligned_pc_table();
    return 0;
}
